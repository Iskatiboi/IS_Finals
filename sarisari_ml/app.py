# ----- Tab 2: Supervised Learning -----
with sales_tab:
    paint_question(
        "How much will we sell tomorrow?",
        "Supervised learning, using a year of days with known sales.",
        "sales",
    )
    sales = load_sales()
    results = load_sales_models()
    metrics = results["metrics"]

    with st.expander("How it works"):
        st.write(
            "We show the computer 80% of the year's days, including each day's "
            "sales. It learns how paydays, weekends, holidays, and rain change "
            "sales. Then we test it on the other 20%, which it has never seen."
        )
        st.write(
            "**Linear Regression** adds up one fixed peso amount per factor. "
            "**Random Forest** averages 100 decision trees and can also learn "
            "combinations of factors."
        )

    st.subheader("Dataset preview")
    st.caption(f"{len(sales)} days of synthetic store data. The first 10 days are shown.")
    st.dataframe(sales.head(10).rename(columns=LABELS), hide_index=True)

    st.subheader("Model comparison on the unseen test days")
    for column, (_, row) in zip(st.columns(2), metrics.iterrows()):
        with column:
            st.markdown(f"**{row['Model']}**")
            mae_column, r2_column = st.columns(2)
            mae_column.metric("MAE (average error)", f"₱{row['MAE (pesos)']:,.2f}")
            r2_column.metric("R² score", f"{row['R2 Score']:.3f}")

    best_model = metrics.loc[metrics["MAE (pesos)"].idxmin(), "Model"]
    st.success(f"{best_model} has the lowest average error on this data.")

    left, right = st.columns(2)
    with left:
        st.subheader("What drives sales?")
        st.caption("How much the Random Forest relied on each input.")
        importances = results["importances"].replace({"feature": LABELS})
        st.bar_chart(
            importances, x="feature", y="importance",
            x_label="Input", y_label="Importance", horizontal=True, sort=False, height=340,
        )
    with right:
        st.subheader("Predicted vs actual")
        st.caption("Sales on the test days, in calendar order.")
        st.line_chart(results["comparison"], x_label="Day of the year", y_label="Sales (pesos)")

    st.subheader("Try a prediction")
    day_names = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
    model_names = ["Random Forest", "Linear Regression"]

    with st.form("prediction_form"):
        col1, col2 = st.columns(2)
        with col1:
            day = st.selectbox("Day of the week", day_names)
            temperature = st.slider("Temperature (°C)", 24.0, 38.0, 31.0, 0.5)
            model_name = st.selectbox("Model", model_names, index=model_names.index(best_model))
        with col2:
            is_payday = st.checkbox("Payday")
            is_holiday = st.checkbox("Holiday")
            is_rainy = st.checkbox("Rainy")
        submitted = st.form_submit_button("Predict Sales", type="primary")

    if submitted:
        model = results["forest"] if model_name == "Random Forest" else results["linear"]
        value = predict_sales(
            model, day_names.index(day), is_payday, is_holiday, is_rainy, temperature
        )
        # Saved so the answer stays on screen after clicking elsewhere.
        st.session_state["prediction"] = (value, model_name)

    if "prediction" in st.session_state:
        value, used_model = st.session_state["prediction"]
        st.html(f'<div class="price-card"><span>Predicted sales</span><strong>₱{value:,.0f}</strong></div>')
        st.caption(f"Predicted by {used_model}.")


