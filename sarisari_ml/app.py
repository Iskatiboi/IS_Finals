# ----- Cached helpers -----
# Streamlit reruns this whole file on every click. Caching saves the results
# so the data and the models are only built once.

@st.cache_data
def load_sales():
    return generate_sales()


@st.cache_data
def load_products():
    return generate_products()


@st.cache_resource
def load_sales_models():
    return train_models(load_sales())


@st.cache_data
def load_clusters():
    products = load_products()
    labeled, summary = cluster_products(products)
    return labeled, summary, compute_elbow(products)


@st.cache_data(show_spinner=False)
def run_agent(episodes):
    """Train the agent, then test what it learned."""
    Q, rewards = train(episodes)
    policy = get_policy(Q)
    daily, total_profit = simulate(policy, days=30, seed=7)
    comparison = compare_policies(policy)
    return {
        "episodes": episodes,
        "rewards": rewards,
        "policy": policy,
        "daily": daily,
        "total_profit": total_profit,
        "comparison": comparison,
    }


